/**
 * The data behind the rich text editor's toolbar.
 *
 * Every select, color picker, emoji panel and symbol panel of the toolbar renders from the tables
 * below, so the module holds no behaviour at all: it imports nothing, has no side effects and every
 * table is a plain constant. The values are the ones the editor's own policies accept —
 * `inlineStyleValue('font-family', …)` takes the stacks of {@link FONT_FAMILY_CHOICES},
 * `inlineStyleValue('font-size', …)` the sizes of {@link FONT_SIZE_CHOICES}, and the color marks
 * take the hex values of {@link HIGHLIGHT_COLOR_GROUPS} and {@link TEXT_COLOR_GROUPS}.
 *
 * A table whose order is part of its meaning is in that order rather than in alphabetical order:
 * {@link BLOCK_TYPE_CHOICES} is a sequence of heading levels and {@link FONT_SIZE_CHOICES} counts
 * up, so neither is sorted. The curated order of an emoji or symbol group is not something the
 * alphabetization rules know about, so the `emojis` and `symbols` arrays carry a disable comment.
 */

/** One choice of a toolbar select: the value the editor stores and the label a user reads. */
export interface RichTextEditorChoice {
  /** Text shown in the select. */
  label: string;
  /** Value the editor stores, in the form its policy accepts. */
  value: string;
}

/** Named colors of the text-color and highlight pickers. */
export interface RichTextEditorColorGroup {
  /** Swatches of the group, in the order the picker shows them. */
  colors: RichTextEditorChoice[];
  /** Title of the group. */
  label: string;
}

/** One group of the emoji picker. */
export interface RichTextEditorEmojiGroup {
  /** Emoji of the group, in the curated order the picker shows them. */
  emojis: { char: string; name: string }[];
  /** Stable key of the group, used as a React key and a test id. */
  key: string;
  /** Title of the group. */
  label: string;
}

/** Paragraph spacing presets. `marginTop`/`marginBottom` are numbers meaning pixels, or null meaning "leave alone". */
export interface RichTextEditorSpacingChoice {
  /** Text shown in the picker. */
  label: string;
  /** Space below the paragraph in pixels, or `null` when the preset leaves it alone. */
  marginBottom: null | number;
  /** Space above the paragraph in pixels, or `null` when the preset leaves it alone. */
  marginTop: null | number;
  /** Value the editor stores. */
  value: string;
}

/** One group of the special-symbol picker, for inserting literal characters. */
export interface RichTextEditorSymbolGroup {
  /** Stable key of the group, used as a React key and a test id. */
  key: string;
  /** Title of the group. */
  label: string;
  /** Symbols of the group, in the order the picker shows them. */
  symbols: { char: string; name: string }[];
}

